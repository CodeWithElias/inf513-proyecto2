-- =====================================================================
-- PROYECTO 2 - Contratación guiada de una proforma
-- Para aprobar una proforma el cliente (o el personal en su nombre) completa:
--   1. datos de la campaña  2. material de cada servicio  3. días y horarios de la agenda
--   4. pago (contado o cuotas). Recién con el pago aprobado la proforma pasa a «aprobada».
--
-- contratacion_servicio: cada servicio a cumplir (un ítem de la proforma; los paquetes se abren en
--   sus tarifas) con la cantidad de emisiones/publicaciones/días y el material elegido.
-- contratacion_espacio:  los espacios de la agenda elegidos para cada servicio. Mientras la
--   contratación no se confirma son una reserva temporal (vence a las 48 h sin cambios);
--   al confirmar se crea la pauta y queda enlazada (id_programacion) para la trazabilidad.
-- Solo agrega tablas; no modifica las del Proyecto 1. Idempotente.
-- =====================================================================

CREATE TABLE IF NOT EXISTS contratacion_servicio (
    id_linea      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proforma   INTEGER NOT NULL REFERENCES proforma (id_proforma) ON DELETE CASCADE,
    id_detalle    INTEGER NOT NULL REFERENCES detalle_proforma (id_detalle) ON DELETE CASCADE,
    id_tarifa     INTEGER NOT NULL REFERENCES tarifa (id_tarifa),
    cantidad      INTEGER NOT NULL CHECK (cantidad > 0),
    id_material   INTEGER REFERENCES material_publicitario (id_material) ON DELETE SET NULL,
    CONSTRAINT ux_contratacion_linea UNIQUE (id_detalle, id_tarifa)
);
CREATE INDEX IF NOT EXISTS ix_contratacion_proforma ON contratacion_servicio (id_proforma);

CREATE TABLE IF NOT EXISTS contratacion_espacio (
    id_reserva       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_linea         INTEGER NOT NULL REFERENCES contratacion_servicio (id_linea) ON DELETE CASCADE,
    id_espacio       INTEGER NOT NULL REFERENCES espacio_publicitario (id_espacio),
    id_programacion  INTEGER REFERENCES programacion_pauta (id_programacion) ON DELETE SET NULL,
    fecha_reserva    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Un espacio no puede estar apartado por dos contrataciones sin confirmar a la vez
CREATE UNIQUE INDEX IF NOT EXISTS ux_reserva_espacio_pendiente ON contratacion_espacio (id_espacio) WHERE id_programacion IS NULL;
CREATE INDEX IF NOT EXISTS ix_reserva_linea ON contratacion_espacio (id_linea);

-- ---------------------------------------------------------------------
-- RBAC: privilegios por rol y menú dinámico
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS privilegio (
    id_privilegio  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(80)  NOT NULL UNIQUE,     -- recurso.accion  (ej. usuarios.crear)
    recurso        VARCHAR(50)  NOT NULL,
    accion         VARCHAR(30)  NOT NULL,
    descripcion    VARCHAR(200),
    modulo         VARCHAR(60)  NOT NULL             -- agrupa en la matriz de permisos
);

CREATE TABLE IF NOT EXISTS rol_privilegio (
    id_rol         INTEGER NOT NULL REFERENCES rol (id_rol) ON DELETE CASCADE,
    id_privilegio  INTEGER NOT NULL REFERENCES privilegio (id_privilegio) ON DELETE CASCADE,
    PRIMARY KEY (id_rol, id_privilegio)
);

CREATE TABLE IF NOT EXISTS menu_item (
    id_menu        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo         VARCHAR(80)  NOT NULL,
    ruta           VARCHAR(150),                     -- NULL en los grupos
    icono          VARCHAR(50),                      -- nombre de ícono lucide-react
    orden          INTEGER NOT NULL DEFAULT 0,
    id_padre       INTEGER REFERENCES menu_item (id_menu) ON DELETE CASCADE,
    codigo_privilegio VARCHAR(80) REFERENCES privilegio (codigo) ON UPDATE CASCADE ON DELETE SET NULL,
    activo         BOOLEAN NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- Bitácora de auditoría (logins, fallos, IP, tráfico por recurso)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bitacora (
    id_bitacora   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario    INTEGER REFERENCES usuario (id_usuario) ON DELETE SET NULL,
    email         VARCHAR(150),
    evento        VARCHAR(30)  NOT NULL,   -- login_ok | login_fallido | logout | acceso | denegado | error
    metodo        VARCHAR(10),
    recurso       VARCHAR(200),            -- patrón de ruta (api/v1/usuarios/{usuario})
    ruta          VARCHAR(500),            -- URL real
    ip            VARCHAR(45),
    user_agent    VARCHAR(300),
    codigo_http   SMALLINT,
    duracion_ms   INTEGER,
    detalle       VARCHAR(500),
    fecha         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_bitacora_evento CHECK (evento IN ('login_ok','login_fallido','logout','acceso','denegado','error'))
);
CREATE INDEX IF NOT EXISTS ix_bitacora_fecha   ON bitacora (fecha);
CREATE INDEX IF NOT EXISTS ix_bitacora_evento  ON bitacora (evento);
CREATE INDEX IF NOT EXISTS ix_bitacora_usuario ON bitacora (id_usuario);

-- Contador de accesos por recurso (lo mantiene un trigger)
CREATE TABLE IF NOT EXISTS contador_recurso (
    recurso        VARCHAR(200) PRIMARY KEY,
    total          BIGINT NOT NULL DEFAULT 0,
    ultimo_acceso  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Contador de visitas por página del sitio (footer)
CREATE TABLE IF NOT EXISTS visita_pagina (
    ruta           VARCHAR(255) PRIMARY KEY,
    total          BIGINT NOT NULL DEFAULT 0,
    ultima_visita  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------
-- Triggers y funciones
-- ---------------------------------------------------------------------

-- Cada acceso registrado en la bitácora incrementa el contador de su recurso.
-- Cada login exitoso actualiza usuario.ultimo_acceso.
CREATE OR REPLACE FUNCTION fn_bitacora_despues_insertar() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.evento = 'acceso' AND NEW.recurso IS NOT NULL THEN
        INSERT INTO contador_recurso (recurso, total, ultimo_acceso)
        VALUES (NEW.recurso, 1, NEW.fecha)
        ON CONFLICT (recurso) DO UPDATE
            SET total = contador_recurso.total + 1,
                ultimo_acceso = EXCLUDED.ultimo_acceso;
    ELSIF NEW.evento = 'login_ok' AND NEW.id_usuario IS NOT NULL THEN
        UPDATE usuario SET ultimo_acceso = NEW.fecha WHERE id_usuario = NEW.id_usuario;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_bitacora_despues_insertar ON bitacora;
CREATE TRIGGER trg_bitacora_despues_insertar
    AFTER INSERT ON bitacora
    FOR EACH ROW EXECUTE FUNCTION fn_bitacora_despues_insertar();

-- Registra una visita a una página y devuelve el total acumulado (atómico).
CREATE OR REPLACE FUNCTION fn_registrar_visita(p_ruta VARCHAR) RETURNS BIGINT AS $$
DECLARE
    v_total BIGINT;
BEGIN
    INSERT INTO visita_pagina (ruta, total, ultima_visita)
    VALUES (p_ruta, 1, CURRENT_TIMESTAMP)
    ON CONFLICT (ruta) DO UPDATE
        SET total = visita_pagina.total + 1,
            ultima_visita = CURRENT_TIMESTAMP
    RETURNING total INTO v_total;
    RETURN v_total;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------
-- Laravel Sanctum (tokens de acceso de la API)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS personal_access_tokens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tokenable_type  VARCHAR(255) NOT NULL,
    tokenable_id    BIGINT NOT NULL,
    name            TEXT NOT NULL,
    token           VARCHAR(64) NOT NULL UNIQUE,
    abilities       TEXT,
    last_used_at    TIMESTAMP(0),
    expires_at      TIMESTAMP(0),
    created_at      TIMESTAMP(0),
    updated_at      TIMESTAMP(0)
);
CREATE INDEX IF NOT EXISTS personal_access_tokens_tokenable_type_tokenable_id_index
    ON personal_access_tokens (tokenable_type, tokenable_id);
CREATE INDEX IF NOT EXISTS personal_access_tokens_expires_at_index
    ON personal_access_tokens (expires_at);

-- =====================================================================
-- PROYECTO 2 - Solicitudes de cuenta de visitantes
-- Un visitante que cotiza puede pedir una cuenta (elige su contraseña).
-- La solicitud queda "pendiente" hasta que el Director o el Administrador
-- la aprueba (se crea su usuario con rol Cliente) o la rechaza.
-- No modifica la tabla visitante del Proyecto 1. Idempotente.
-- =====================================================================

CREATE TABLE IF NOT EXISTS solicitud_cuenta (
    id_solicitud     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_visitante     INTEGER NOT NULL REFERENCES visitante (id_visitante) ON DELETE CASCADE,
    password_hash    VARCHAR(255),          -- bcrypt; se borra al aprobar o rechazar
    estado           VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    motivo_rechazo   VARCHAR(300),
    id_usuario       INTEGER REFERENCES usuario (id_usuario) ON DELETE SET NULL,  -- cuenta creada al aprobar
    id_revisor       INTEGER REFERENCES usuario (id_usuario) ON DELETE SET NULL,  -- quién aprobó o rechazó
    fecha_solicitud  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_revision   TIMESTAMP,
    CONSTRAINT ck_solicitud_estado CHECK (estado IN ('pendiente', 'aprobada', 'rechazada'))
);
-- Un visitante solo puede tener una solicitud pendiente a la vez
CREATE UNIQUE INDEX IF NOT EXISTS ux_solicitud_pendiente ON solicitud_cuenta (id_visitante) WHERE estado = 'pendiente';
CREATE INDEX IF NOT EXISTS ix_solicitud_usuario ON solicitud_cuenta (id_usuario);
CREATE INDEX IF NOT EXISTS ix_solicitud_estado ON solicitud_cuenta (estado);

-- Privilegios
INSERT INTO privilegio (codigo, recurso, accion, descripcion, modulo) VALUES
    ('solicitudes.ver',    'solicitudes', 'ver',    'Ver solicitudes de cuenta de visitantes',               'Comercial'),
    ('solicitudes.editar', 'solicitudes', 'editar', 'Aprobar o rechazar solicitudes de cuenta de visitantes', 'Comercial')
ON CONFLICT (codigo) DO UPDATE SET descripcion = EXCLUDED.descripcion, modulo = EXCLUDED.modulo;

INSERT INTO rol_privilegio (id_rol, id_privilegio)
SELECT r.id_rol, p.id_privilegio
FROM rol r JOIN privilegio p ON p.codigo IN ('solicitudes.ver', 'solicitudes.editar')
WHERE r.nombre IN ('Administrador', 'Director')
ON CONFLICT DO NOTHING;

-- Menú: Comercial → Solicitudes de cuenta (primera opción del grupo)
INSERT INTO menu_item (titulo, ruta, icono, orden, id_padre, codigo_privilegio)
SELECT 'Solicitudes de cuenta', '/solicitudes', 'UserPlus', 0, g.id_menu, 'solicitudes.ver'
FROM menu_item g
WHERE g.titulo = 'Comercial' AND g.id_padre IS NULL
  AND NOT EXISTS (SELECT 1 FROM menu_item WHERE ruta = '/solicitudes');

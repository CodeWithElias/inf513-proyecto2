-- ---------------------------------------------------------------------
-- 1. Métodos de pago registrados por el usuario (nunca guarda PAN ni CVV)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS metodo_pago (
    id_metodo       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      INTEGER NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    tipo            VARCHAR(30)  NOT NULL,          -- tarjeta | qr | billetera
    marca           VARCHAR(40),                    -- Visa, Mastercard, Amex, QR Simple, Tigo Money...
    ultimos4        VARCHAR(4),                     -- solo últimos 4 dígitos para tarjetas
    titular         VARCHAR(150) NOT NULL,
    mes_exp         SMALLINT,
    anio_exp        SMALLINT,
    token_simulado  VARCHAR(80)  NOT NULL,
    predeterminado  BOOLEAN      NOT NULL DEFAULT FALSE,
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_metodo_pago_tipo CHECK (tipo IN ('tarjeta', 'qr', 'billetera')),
    CONSTRAINT ck_metodo_pago_mes  CHECK (mes_exp IS NULL OR (mes_exp BETWEEN 1 AND 12))
);
CREATE INDEX IF NOT EXISTS ix_metodo_pago_usuario ON metodo_pago (id_usuario);

-- ---------------------------------------------------------------------
-- 2. Planes de pago en cuotas asociados a una proforma
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS plan_pago (
    id_plan         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      INTEGER      NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    id_proforma     INTEGER      NOT NULL REFERENCES proforma (id_proforma) ON DELETE CASCADE,
    monto_total     NUMERIC(12,2) NOT NULL,
    nro_cuotas      INTEGER      NOT NULL,
    frecuencia      VARCHAR(20)  NOT NULL DEFAULT 'mensual',  -- mensual | quincenal | semanal
    fecha_inicio    DATE         NOT NULL DEFAULT CURRENT_DATE,
    estado          VARCHAR(20)  NOT NULL DEFAULT 'activo',   -- activo | completado | cancelado
    fecha_registro  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_plan_pago_cuotas CHECK (nro_cuotas BETWEEN 2 AND 24),
    CONSTRAINT ck_plan_pago_frec   CHECK (frecuencia IN ('mensual', 'quincenal', 'semanal')),
    CONSTRAINT ck_plan_pago_estado CHECK (estado IN ('activo', 'completado', 'cancelado'))
);
CREATE INDEX IF NOT EXISTS ix_plan_pago_usuario  ON plan_pago (id_usuario);
CREATE INDEX IF NOT EXISTS ix_plan_pago_proforma ON plan_pago (id_proforma);

-- ---------------------------------------------------------------------
-- 3. Cuotas de cada plan de pago
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS cuota (
    id_cuota           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_plan            INTEGER      NOT NULL REFERENCES plan_pago (id_plan) ON DELETE CASCADE,
    nro                INTEGER      NOT NULL,
    monto              NUMERIC(12,2) NOT NULL,
    fecha_vencimiento  DATE         NOT NULL,
    estado             VARCHAR(20)  NOT NULL DEFAULT 'pendiente', -- pendiente | pagada | vencida
    fecha_pago         TIMESTAMP,
    CONSTRAINT uq_cuota_plan_nro UNIQUE (id_plan, nro),
    CONSTRAINT ck_cuota_estado   CHECK (estado IN ('pendiente', 'pagada', 'vencida'))
);
CREATE INDEX IF NOT EXISTS ix_cuota_plan ON cuota (id_plan);

-- ---------------------------------------------------------------------
-- 4. Transacciones de pago (pago único de proforma o pago de cuota)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS transaccion_pago (
    id_transaccion       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario           INTEGER      NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    id_metodo            INTEGER      REFERENCES metodo_pago (id_metodo) ON DELETE SET NULL,
    id_proforma          INTEGER      REFERENCES proforma (id_proforma) ON DELETE SET NULL,
    id_cuota             INTEGER      REFERENCES cuota (id_cuota) ON DELETE SET NULL,
    monto                NUMERIC(12,2) NOT NULL,
    estado               VARCHAR(20)  NOT NULL,                -- aprobada | rechazada
    codigo_autorizacion  VARCHAR(30),
    mensaje              VARCHAR(255),
    fecha                TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_transaccion_estado CHECK (estado IN ('aprobada', 'rechazada'))
);
CREATE INDEX IF NOT EXISTS ix_transaccion_usuario  ON transaccion_pago (id_usuario);
CREATE INDEX IF NOT EXISTS ix_transaccion_proforma ON transaccion_pago (id_proforma);
CREATE INDEX IF NOT EXISTS ix_transaccion_cuota    ON transaccion_pago (id_cuota);
CREATE INDEX IF NOT EXISTS ix_transaccion_fecha    ON transaccion_pago (fecha);

-- ---------------------------------------------------------------------
-- 5. Trigger trg_cuota_pagada
--    Cuando una cuota pasa a 'pagada', registra fecha_pago y si todas
--    las cuotas del plan ya están pagadas marca el plan como 'completado'.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_cuota_pagada() RETURNS TRIGGER AS $$
DECLARE
    v_pendientes INTEGER;
BEGIN
    IF NEW.estado = 'pagada' AND OLD.estado IS DISTINCT FROM 'pagada' THEN
        IF NEW.fecha_pago IS NULL THEN
            UPDATE cuota SET fecha_pago = CURRENT_TIMESTAMP WHERE id_cuota = NEW.id_cuota;
        END IF;

        SELECT COUNT(*) INTO v_pendientes
        FROM cuota
        WHERE id_plan = NEW.id_plan AND estado <> 'pagada';

        IF v_pendientes = 0 THEN
            UPDATE plan_pago SET estado = 'completado' WHERE id_plan = NEW.id_plan;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_cuota_pagada ON cuota;
CREATE TRIGGER trg_cuota_pagada
    AFTER UPDATE OF estado ON cuota
    FOR EACH ROW EXECUTE FUNCTION fn_cuota_pagada();

